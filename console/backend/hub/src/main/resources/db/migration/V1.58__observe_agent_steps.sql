-- Platform authorization/projection and durable export backlog. No trace TTL deletes task files.
CREATE TABLE oa_run_step (
    id bigint NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_id varchar(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    environment varchar(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    run_id varchar(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    attempt_no int NOT NULL,
    step_id varchar(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    parent_step_id varchar(128) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
    kind varchar(16) NOT NULL,
    name varchar(128) NOT NULL,
    started_at timestamp(3) NOT NULL,
    ended_at timestamp(3) DEFAULT NULL,
    duration_ms bigint DEFAULT NULL,
    status varchar(16) NOT NULL DEFAULT 'running',
    usage_source varchar(24) NOT NULL,
    input_tokens bigint DEFAULT NULL,
    output_tokens bigint DEFAULT NULL,
    cache_read_tokens bigint DEFAULT NULL,
    cache_write_tokens bigint DEFAULT NULL,
    start_json json NOT NULL,
    finish_json json DEFAULT NULL,
    start_hash char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    finish_hash char(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
    export_state varchar(16) NOT NULL DEFAULT 'pending',
    received_at timestamp(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    UNIQUE KEY uq_oa_step(run_id,attempt_no,step_id),
    KEY ix_oa_step_period(tenant_id,environment,kind,ended_at),
    KEY ix_oa_step_export(export_state,id),
    CONSTRAINT fk_oa_step_run FOREIGN KEY(tenant_id,environment,run_id) REFERENCES oa_agent_run(tenant_id,environment,run_id),
    CONSTRAINT ck_oa_step_kind CHECK(kind IN ('agent','chain','model','tool','skill','artifact')),
    CONSTRAINT ck_oa_step_status CHECK(status IN ('running','succeeded','failed','interrupted')),
    CONSTRAINT ck_oa_step_usage CHECK(usage_source IN ('provider','unknown','not_applicable','aggregate')),
    CONSTRAINT ck_oa_step_export CHECK(export_state IN ('pending','delivered'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
